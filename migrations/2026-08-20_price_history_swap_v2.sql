-- ── 6) Wochen-Rollup + Wochenjob (ebenfalls zurueckgerollt gewesen) ────────
create or replace function public.price_history_rollup(p_keep_days int default 90)
returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  -- Aelter als p_keep_days: je Karte und Kalenderwoche nur den JUENGSTEN
  -- Punkt behalten. Der letzte Stand einer Karte bleibt immer (rn = 1).
  delete from public.price_history ph
  using (
    select id,
           row_number() over (
             partition by player_slug, scarcity, eligibility,
                          date_trunc('week', recorded_at::timestamp)
             order by recorded_at desc, id desc) as rn
    from public.price_history
    where recorded_at < current_date - p_keep_days
  ) t
  where ph.id = t.id and t.rn > 1;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.price_history_rollup(int) from public;

do $$
begin
  create extension if not exists pg_cron;
  perform cron.schedule('price_history_rollup_weekly', '30 6 * * 1',
                        'select public.price_history_rollup(90)');
exception when others then
  raise notice 'pg_cron nicht verfuegbar (%): bitte melden, dann haengen wir den Job an den Harvester', sqlerrm;
end $$;

-- ── Kontrolle (letzte Ausgabe des Laufs) ───────────────────────────────────
select count(*)                                                        as zeilen,
       pg_size_pretty(pg_total_relation_size('public.price_history'))  as price_history_gesamt,
       (select count(*) from (
          select price, lag(price) over (partition by player_slug, scarcity, eligibility
                                         order by recorded_at) as prev
          from public.price_history) t
        where prev is not null and price = prev)                       as verbliebene_duplikate,
       (select count(*) from pg_indexes
        where schemaname = 'public' and tablename = 'price_history')   as indizes_anzahl;
