-- ── 1) Frische Tabelle, Behalter kopieren ──────────────────────────────────
create table public.price_history_neu
  (like public.price_history including defaults including identity including constraints);

insert into public.price_history_neu
select ph.* from public.price_history ph
where ph.id in (
  select id from (
    select id, price,
           lag(price) over (partition by player_slug, scarcity, eligibility
                            order by recorded_at) as prev
    from public.price_history
  ) t
  where prev is null or price is distinct from prev
);

-- ── 2) Geliehenen Zaehler abloesen, tauschen, eigenes Identity ─────────────
alter table public.price_history_neu alter column id drop default;
drop table public.price_history;      -- nimmt alte Sequenz + tote Indizes mit
alter table public.price_history_neu rename to price_history;
alter table public.price_history
  alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.price_history', 'id'),
              (select coalesce(max(id), 1) from public.price_history));

